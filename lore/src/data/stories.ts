/**
 * Builds a timed placeholder transcript. `original` is the story's language
 * code; when we have no placeholder text in that language the original
 * column is left empty, which the site shows as "transcription in progress".
 */
function demoTranscript(original: string, extra: string[] = [], pace = 7): TranscriptSegment[] {
  const en = DEMO_LINES.en;
  const orig = original === "en" ? en : DEMO_LINES[original];
  return en.map((english, i) => {
    const translations: Record<string, string> = {};
    for (const code of extra) if (DEMO_LINES[code]) translations[code] = DEMO_LINES[code][i];
    return {
      start: 3 + i * pace,
      end: 3 + (i + 1) * pace - 0.6,
      original: orig?.[i],
      english,
      translations: Object.keys(translations).length ? translations : undefined,
    };
  });
}

